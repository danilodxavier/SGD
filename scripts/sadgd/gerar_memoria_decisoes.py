def main():
    DESTINO.parent.mkdir(parents=True, exist_ok=True)
    with DESTINO.open("w", encoding="utf-8", newline="\n") as f:
        for cod, data, contrato, titulo, contexto, decisao, fund, resultado, aval in DECISOES:
            f.write(json.dumps({"codigo": cod, "data": data, "contrato": contrato,
                                "titulo": f"DECISÃO DA GESTÃO {cod} — {titulo}", "contexto": contexto,
                                "decisao": decisao, "fundamentos": fund, "resultado": resultado,
                                "avaliacao_resultado": aval, "decisor_perfil": "Secretário de Estado",
                                "corpus_origem": "sintetico"}, ensure_ascii=False) + "\n")
    codigos = {d[0] for d in DECISOES}
    for nome, prefixo in (("validacao", "PV"), ("teste", "PT")):
        with (GOLDEN / f"precedentes_{nome}.jsonl").open("w", encoding="utf-8", newline="\n") as f:
            for pid, pergunta, esperados in PERGUNTAS:
                if pid.startswith(prefixo):
                    assert set(esperados) <= codigos, pid
                    f.write(json.dumps({"id": pid, "pergunta": pergunta, "esperados": esperados},
                                       ensure_ascii=False) + "\n")
    print(f"[OK] {len(DECISOES)} decisões; {len(PERGUNTAS)} perguntas "
          f"({sum(1 for p in PERGUNTAS if not p[2])} sem precedente)")


if __name__ == "__main__":
    main()
